#: Bump when the manifest layout changes incompatibly. A loader that finds a
#: version it does not know refuses rather than guessing, because a silently
#: mis-parsed corpus produces numbers rather than errors.
MANIFEST_VERSION = "1.0"


class Provenance(str, Enum):
    """Where a corpus's speech came from.

    This is the field that stops a simulated number reaching a paper. It is
    stored on the manifest rather than inferred, so a corpus built by
    `from_simulation` cannot be relabelled by moving files around.
    """

    RECORDED = "RECORDED"
    """Human speakers, recorded under the protocol. The only reportable kind."""

    SIMULATED = "SIMULATED"
    """Generated by `simulation.py`. Speakers differ by construction."""

    SCRIPTED = "SCRIPTED"
    """Human speakers reading authored text (`participant_scripts/`).

    The audio is real -- real voices, microphones and rooms -- so the acoustic,
    liveness and integrity branches are unaffected by this label and a
    scripted corpus measures them honestly.

    The *content* is not. A CSBG built from read speech recovers the profile
    the script author wrote, so a scripted run cannot support §5.1's claim that
    speakers have stable code-switching habits: it would be answering a
    question with its own premise. What it does support is word-level LID
    accuracy (every token's language is known, making it a labelled evaluation
    set) and whether the pipeline recovers a *planted* profile end to end --
    the negative control for §5.1, since a pipeline that cannot find a profile
    we wrote will not find one we did not.

    Kept distinct from SIMULATED because the failure modes do not overlap:
    simulated speech has no acoustics at all, scripted speech has real
    acoustics and authored words."""

    AUGMENTED = "AUGMENTED"
    """Recorded speech with signal augmentation (noise, codec, room). Usable
    for robustness rows, never for the headline EER: the augmented copies are
    not independent speakers and inflate the trial count without adding
    speakers."""

    @property
    def is_reportable(self) -> bool:
        return self is Provenance.RECORDED


class AnnotationSource(str, Enum):
    """How a token stream got its language and semantic-class tags."""

    HUMAN = "HUMAN"
    """Hand-annotated. The validation set, and the ceiling everything else is
    measured against."""

    LLM = "LLM"
    """`lid.llm` tagging pass, rules taking precedence on script evidence."""

    RULES = "RULES"
    """`lid.rules` only. Tamil script resolves; unresolved Latin tokens are
    guessed, which is exactly what `PipelineStats.is_corpus_grade` refuses."""

    SYNTHETIC = "SYNTHETIC"
    """Tags came from the generating distribution, not from a tagger."""


class Environment(str, Enum):
    """Recording condition, for the §5.5 fairness slice.

    Deliberately coarse. A free-text field would produce thirty groups of one
    and no slice large enough to compare, and `fairness_slices` drops groups
    under `min_trials` anyway.
    """

    QUIET_ROOM = "QUIET_ROOM"
    OFFICE = "OFFICE"
    CORRIDOR = "CORRIDOR"
    OUTDOOR = "OUTDOOR"


