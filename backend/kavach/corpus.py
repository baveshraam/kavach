@dataclass(frozen=True, slots=True)
class ClassCoverage:
    semantic_class: SemanticClass
    n_tokens: int
    n_speakers_with_own_evidence: int
    """Speakers with enough tokens of this class that their own observations
    outweigh the backoff prior."""


@dataclass(frozen=True, slots=True)
class PromptCoverage:
    prompt_id: str
    n_utterances: int
    mean_tokens: float
    """§5.1.1 asks for this beside every per-class result: a prompt whose mean
    answer is a couple of tokens long has no wrapper for the CSBG to read, and
    its null result says nothing about the hypothesis."""

    hit_rate: float
    """Share of this prompt's utterances containing at least one token of a
    class the prompt was written to elicit. A low value is a broken question."""


@dataclass(slots=True)
class CoverageReport:
    """Whether the recordings can actually support the analysis.

    Run this after the pilot, not after full collection. Every problem it
    names is fixed by changing the prompts and recording again, which is
    affordable at five speakers and not at thirty.
    """

    classes: list[ClassCoverage] = field(default_factory=list)
    prompts: list[PromptCoverage] = field(default_factory=list)
    total_tokens: int = 0
    total_choice_tokens: int = 0
    n_speakers: int = 0
    min_tokens_for_own_evidence: float = 0.0

    def starved_classes(self) -> list[ClassCoverage]:
        """Elicitable classes no speaker has own-evidence for.

        These contribute the backoff prior for everyone, which is identical
        across speakers and therefore carries no biometric signal at all.
        """
        return [
            c
            for c in self.classes
            if c.semantic_class in ELICITABLE_CLASSES
            and c.n_speakers_with_own_evidence == 0
        ]

    def wrapperless_prompts(self, *, min_mean_tokens: float = 5.0) -> list[PromptCoverage]:
        """Prompts producing answers too short for the CSBG to read.

        `min_mean_tokens` is not a tuned threshold: `build_trials` marks the
        CSBG branch unavailable below `min_scored_tokens=5`, so a prompt whose
        *mean* answer is under that produces unscoreable probes more often than
        not. The default tracks that constant; pass the real one if it changes.
        """
        return [
            p
            for p in self.prompts
            if p.mean_tokens < min_mean_tokens
            and PROMPTS_BY_ID.get(p.prompt_id, None) is not None
            and PROMPTS_BY_ID[p.prompt_id].elicits_phrase
        ]

    def to_markdown(self) -> str:
        lines = [
            "## Corpus coverage",
            "",
            f"{self.n_speakers} speakers | {self.total_tokens} tokens "
            f"({self.total_choice_tokens} language choices)",
            "",
            "A class needs about "
            f"{self.min_tokens_for_own_evidence:.0f} observations before a speaker's "
            "own evidence outweighs the backoff prior (SmoothingConfig.class_alpha).",
            "",
            "| Class | Tokens | Speakers with own evidence |",
            "|---|---|---|",
        ]
        lines.extend(
            f"| {c.semantic_class.value} | {c.n_tokens} | "
            f"{c.n_speakers_with_own_evidence}/{self.n_speakers} |"
            for c in self.classes
        )

        if self.prompts:
            lines += [
                "",
                "| Prompt | Utterances | Mean tokens | Target hit rate |",
                "|---|---|---|---|",
            ]
            lines.extend(
                f"| {p.prompt_id} | {p.n_utterances} | {p.mean_tokens:.1f} | "
                f"{p.hit_rate:.0%} |"
                for p in self.prompts
            )

        starved = self.starved_classes()
        if starved:
            lines += [
                "",
                "**Starved elicitable classes** -- no speaker has enough tokens for "
                "their own evidence to outweigh the prior, so these classes are "
                "identical across speakers and carry no signal:",
                "",
            ]
            lines.extend(f"- {c.semantic_class.value} ({c.n_tokens} tokens)" for c in starved)

        thin = self.wrapperless_prompts()
        if thin:
            lines += [
                "",
                "**Prompts producing answers too short to score** (§5.1.1 -- the "
                "fact is stealable, the wrapper is the biometric):",
                "",
            ]
            lines.extend(f"- {p.prompt_id} (mean {p.mean_tokens:.1f} tokens)" for p in thin)

        return "\n".join(lines)


def coverage_report(
    corpus: Corpus, *, smoothing: SmoothingConfig | None = None
) -> CoverageReport:
    """Per-class and per-prompt coverage of a corpus.

    The own-evidence threshold is read from `SmoothingConfig.class_alpha`
    rather than written here. That is deliberate, and it is the lesson of the
    two miscalibrated floors in PROJECT.md §5.1: a constant that thresholds
    another module's behaviour must be derived from that module, or it drifts
    the first time the other one is tuned.
    """
    smoothing = smoothing or SmoothingConfig()
    alpha = smoothing.class_alpha

    per_speaker_class: dict[str, Counter[SemanticClass]] = {}
    class_totals: Counter[SemanticClass] = Counter()
    prompt_lengths: dict[str, list[int]] = {}
    prompt_hits: dict[str, list[bool]] = {}
    total_tokens = 0
    total_choice = 0

    for u in corpus.annotated():
        assert u.tokens is not None  # guarded by `annotated`
        total_tokens += len(u.tokens)
        counter = per_speaker_class.setdefault(u.speaker_id, Counter())

        present: set[SemanticClass] = set()
        for tok in u.tokens:
            present.add(tok.semantic_class)
            if tok.language.is_language_choice:
                total_choice += 1
                counter[tok.semantic_class] += 1
                class_totals[tok.semantic_class] += 1

        if u.prompt_id:
            prompt_lengths.setdefault(u.prompt_id, []).append(len(u.tokens))
            prompt = PROMPTS_BY_ID.get(u.prompt_id)
            if prompt is not None:
                prompt_hits.setdefault(u.prompt_id, []).append(
                    bool(present & set(prompt.target_classes))
                )

    classes = [
        ClassCoverage(
            semantic_class=cls_,
            n_tokens=class_totals.get(cls_, 0),
            n_speakers_with_own_evidence=sum(
                1 for c in per_speaker_class.values() if c.get(cls_, 0) >= alpha
            ),
        )
        for cls_ in SemanticClass
    ]

    prompts = [
        PromptCoverage(
            prompt_id=pid,
            n_utterances=len(lengths),
            mean_tokens=sum(lengths) / len(lengths) if lengths else 0.0,
            hit_rate=(
                sum(prompt_hits.get(pid, [])) / len(prompt_hits[pid])
                if prompt_hits.get(pid)
                else 0.0
            ),
        )
        for pid, lengths in sorted(prompt_lengths.items())
    ]

    return CoverageReport(
        classes=classes,
        prompts=prompts,
        total_tokens=total_tokens,
        total_choice_tokens=total_choice,
        n_speakers=len(per_speaker_class),
        min_tokens_for_own_evidence=alpha,
    )


