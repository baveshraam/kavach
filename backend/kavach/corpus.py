"""The corpus layer -- where recorded human speech enters the system.

`simulation.py` currently occupies this slot and says in its own docstring
that nothing it produces may be reported. This module is the thing that
replaces it: a manifest format for real recordings, a loader that emits the
same `list[UtteranceTokens]` shape `eval.ablation.build_trials` already
consumes, and the elicitation protocol the recordings must follow.

WHY A MANIFEST AND NOT A DIRECTORY CONVENTION
---------------------------------------------
Because the evaluation needs facts that a filename cannot carry. Which
*session* an utterance came from decides whether a trial measures
cross-session stability or the same microphone twice (§5.3). Which *device*
and *environment* it was recorded in is the fairness audit (§5.5). Which
*prompt* elicited it decides whether a null result is a property of the
speaker or of the question (§5.1.1). Encoding those in paths means every
consumer re-parses them, and the day one speaker's folder is named differently
the evaluation silently changes meaning.

THE SPLIT THAT MATTERS
----------------------
`eval.ablation` already refuses to split dev/test by trial instead of by
speaker. This module refuses the analogous mistake one level down: **enrolment
and probe speech are split by session, never by utterance.** Two utterances
from one sitting share a microphone, a room, a mood and a topic. Enrolling on
some and probing with the others measures how well the estimator memorises a
recording session, and it flatters every number downstream. `split_sessions`
holds out a whole session and reports the speakers it had to drop for lacking
a second one.

WHAT IT REFUSES TO CERTIFY
--------------------------
A manifest carries its own `Provenance` and its own annotation quality, and
`Corpus.reportability()` returns the reasons it is not publishable rather than
a bare bool. Three states are distinguished on purpose, because they fail
differently:

  - **simulated** -- speakers differ by construction; not evidence about humans;
  - **un-annotated** -- audio recorded, tagging not run; a real intermediate
    state in a collection week, and one that must not silently score as an
    empty graph;
  - **guessed annotation** -- the LID pipeline fell back for some tokens, which
    `lid.pipeline.PipelineStats.is_corpus_grade` already refuses. The same
    definition is used here rather than a second one.

Consent is enforced, not documented. A RECORDED speaker without a consent
reference makes the manifest invalid -- see §9 of the proposal and the reason
`data/` is git-ignored in its entirety.
"""

