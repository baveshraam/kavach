@dataclass(slots=True)
class SessionSplit:
    """Enrolment and probe speech, split by session.

    `dropped_speakers` is part of the result rather than a warning on the side,
    because a split that quietly loses a third of the population changes what
    the EER is an EER *of*, and the number is needed in the paper's methods
    paragraph.
    """

    enrolment: dict[str, list[UtteranceTokens]] = field(default_factory=dict)
    probes: dict[str, list[UtteranceTokens]] = field(default_factory=dict)
    enrolment_sessions: dict[str, list[str]] = field(default_factory=dict)
    probe_sessions: dict[str, list[str]] = field(default_factory=dict)
    dropped_speakers: list[str] = field(default_factory=list)
    cross_session: bool = True

    def summary(self) -> str:
        kind = "cross-session" if self.cross_session else "within-session"
        dropped = (
            f" | dropped {len(self.dropped_speakers)} for having one session"
            if self.dropped_speakers
            else ""
        )
        return (
            f"{kind}: {len(self.enrolment)} speakers, "
            f"{sum(len(v) for v in self.enrolment.values())} enrolment / "
            f"{sum(len(v) for v in self.probes.values())} probe utterances{dropped}"
        )


def split_sessions(
    corpus: Corpus,
    *,
    n_probe_sessions: int = 1,
    allow_within_session: bool = False,
    within_session_probe_fraction: float = 0.3,
) -> SessionSplit:
    """Split each speaker's speech into enrolment and probe sets.

    **By session, never by utterance.** Two utterances from one sitting share
    a microphone, a room, a topic and a mood, so a within-session split
    measures how well the estimator memorises a recording session. The number
    that comes out is not wrong so much as answering a different question --
    and it is the more flattering one, which is why it needs an explicit
    argument to obtain.

    Speakers with too few sessions are dropped and named. Falling back to a
    within-session split for those speakers would be worse than dropping them:
    the corpus would then contain two kinds of trial scored on one scale, and
    the mixture would be invisible in the result.

    Args:
        corpus: Loaded corpus.
        n_probe_sessions: Sessions held out per speaker, taken from the most
            recent. More than one costs enrolment speech; §5.3 wants the gap
            between enrolment and probe to be as long as the corpus allows.
        allow_within_session: Permit the flattering split for speakers with a
            single session. Off by default. When on, the result is marked
            `cross_session=False` and every consumer must say so.
        within_session_probe_fraction: Trailing share of a session's utterances
            used as probes when `allow_within_session` is set.

    Returns:
        A `SessionSplit`. `enrolment` and `probes` plug straight into
        `eval.ablation.build_trials`.
    """
    if n_probe_sessions < 1:
        raise ValueError(f"n_probe_sessions must be >= 1, got {n_probe_sessions}")

    split = SessionSplit(cross_session=not allow_within_session)

    for speaker_id in corpus.speaker_ids:
        sessions = corpus.sessions_of(speaker_id)

        if len(sessions) > n_probe_sessions:
            enrol_ids = [s.session_id for s in sessions[:-n_probe_sessions]]
            probe_ids = [s.session_id for s in sessions[-n_probe_sessions:]]
            enrol = _tokens_for(corpus, speaker_id, enrol_ids)
            probe = _tokens_for(corpus, speaker_id, probe_ids)
        elif allow_within_session and sessions:
            all_ids = [s.session_id for s in sessions]
            utterances = _tokens_for(corpus, speaker_id, all_ids)
            cut = int(len(utterances) * (1.0 - within_session_probe_fraction))
            enrol, probe = utterances[:cut], utterances[cut:]
            enrol_ids = probe_ids = all_ids
        else:
            split.dropped_speakers.append(speaker_id)
            continue

        if not enrol or not probe:
            split.dropped_speakers.append(speaker_id)
            continue

        split.enrolment[speaker_id] = enrol
        split.probes[speaker_id] = probe
        split.enrolment_sessions[speaker_id] = enrol_ids
        split.probe_sessions[speaker_id] = probe_ids

    return split


def _tokens_for(
    corpus: Corpus, speaker_id: str, session_ids: Sequence[str]
) -> list[UtteranceTokens]:
    """Annotated utterances for one speaker across sessions, in manifest order."""
    wanted = set(session_ids)
    return [
        u.to_utterance_tokens()
        for u in corpus.utterances
        if u.speaker_id == speaker_id and u.session_id in wanted and u.is_annotated
    ]


