def from_simulation(
    sim: Any,
    *,
    name: str = "simulated",
    sessions_per_speaker: int = 2,
) -> Corpus:
    """Wrap a `simulation.SimulatedCorpus` in the corpus interface.

    This exists so the corpus code path is the *only* path -- the experiment
    runner loads a `Corpus` whether or not any human has been recorded, and
    the day the recordings land nothing downstream changes except which loader
    produced the object.

    The result is stamped `Provenance.SIMULATED`, so `reportability` refuses
    it and every table built from it carries the reason. That is the point:
    the bridge makes simulated data convenient to run and impossible to
    report by accident.

    Args:
        sim: A `simulation.SimulatedCorpus`.
        name: Corpus name.
        sessions_per_speaker: How many sessions to spread the enrolment
            utterances over. The simulator has no notion of a session, so this
            is a fiction -- it makes the *plumbing* of a cross-session split
            exercisable, and nothing about the resulting speech is actually
            cross-session. Do not read a §5.3 number off it.
    """
    if sessions_per_speaker < 1:
        raise ValueError(
            f"sessions_per_speaker must be >= 1, got {sessions_per_speaker}"
        )

    corpus = Corpus(
        name=name,
        provenance=Provenance.SIMULATED,
        notes=(
            "Generated by kavach.simulation. Sessions are a fiction introduced by "
            "corpus.from_simulation so the cross-session split can be exercised; "
            "the speech behind them is i.i.d. from one profile and shows none of "
            "the drift a real second session would."
        ),
    )

    for speaker_id in sim.speaker_ids:
        corpus.speakers.append(
            SpeakerRecord(speaker_id=speaker_id, consent_ref="n/a (simulated)")
        )

        enrolment = list(sim.enrolment.get(speaker_id, []))
        chunks = _chunk(enrolment, sessions_per_speaker)
        for idx, chunk in enumerate(chunks):
            session_id = f"{speaker_id}_s{idx:02d}"
            corpus.sessions.append(
                SessionRecord(
                    session_id=session_id,
                    speaker_id=speaker_id,
                    recorded_on=f"1970-01-{idx + 1:02d}",
                    device="simulated",
                    environment=Environment.QUIET_ROOM,
                )
            )
            corpus.utterances.extend(
                _utterance_record(u, session_id, speaker_id) for u in chunk
            )

        # Trial utterances become the final session, which is what
        # `split_sessions` holds out as probes.
        trials = list(sim.trials.get(speaker_id, []))
        if trials:
            session_id = f"{speaker_id}_s{len(chunks):02d}"
            corpus.sessions.append(
                SessionRecord(
                    session_id=session_id,
                    speaker_id=speaker_id,
                    recorded_on=f"1970-01-{len(chunks) + 1:02d}",
                    device="simulated",
                    environment=Environment.QUIET_ROOM,
                )
            )
            corpus.utterances.extend(
                _utterance_record(u, session_id, speaker_id) for u in trials
            )

    return corpus


def _utterance_record(
    utt: UtteranceTokens, session_id: str, speaker_id: str
) -> UtteranceRecord:
    return UtteranceRecord(
        utterance_id=utt.utterance_id,
        session_id=session_id,
        speaker_id=speaker_id,
        transcript=utt.transcript,
        duration_sec=len(utt.tokens) * 0.3,
        tokens=list(utt.tokens),
        annotation_source=AnnotationSource.SYNTHETIC,
    )


def _chunk(items: list[UtteranceTokens], n: int) -> list[list[UtteranceTokens]]:
    """Split into `n` near-equal contiguous chunks, dropping empty ones."""
    if not items:
        return []
    n = max(1, min(n, len(items)))
    size, extra = divmod(len(items), n)
    out: list[list[UtteranceTokens]] = []
    start = 0
    for i in range(n):
        stop = start + size + (1 if i < extra else 0)
        out.append(items[start:stop])
        start = stop
    return [c for c in out if c]


