def load_manifest(path: str | Path) -> Corpus:
    """Read a manifest from disk.

    The corpus root is the manifest's parent directory, so `audio_path` stays
    relative and the whole tree can be moved -- which it will be, because it
    holds voiceprints and lives outside version control.

    Raises:
        ValueError: On an unknown manifest version. Guessing at an unfamiliar
            layout produces a corpus that loads and is wrong.
    """
    path = Path(path)
    data = json.loads(path.read_text(encoding="utf-8"))
    version = data.get("manifest_version", "")
    if version != MANIFEST_VERSION:
        raise ValueError(
            f"{path}: manifest version {version!r}, this code reads {MANIFEST_VERSION!r}"
        )
    return _corpus_from_dict(data, root=path.parent)


def save_manifest(corpus: Corpus, path: str | Path) -> Path:
    """Write a manifest, creating parent directories."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(corpus.to_dict(), ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return path


def _corpus_from_dict(data: dict[str, Any], *, root: Path | None = None) -> Corpus:
    speakers = [
        SpeakerRecord(
            speaker_id=s["speaker_id"],
            consent_ref=s.get("consent_ref", ""),
            gender=s.get("gender", ""),
            age_band=s.get("age_band", ""),
            dominant_language=s.get("dominant_language", ""),
            script_id=s.get("script_id", ""),
            notes=s.get("notes", ""),
        )
        for s in data.get("speakers", [])
    ]
    sessions = [
        SessionRecord(
            session_id=s["session_id"],
            speaker_id=s["speaker_id"],
            recorded_on=s.get("recorded_on", ""),
            device=s.get("device", ""),
            environment=(
                Environment(s["environment"]) if s.get("environment") else None
            ),
        )
        for s in data.get("sessions", [])
    ]
    utterances = [
        UtteranceRecord(
            utterance_id=u["utterance_id"],
            session_id=u["session_id"],
            speaker_id=u["speaker_id"],
            prompt_id=u.get("prompt_id", ""),
            audio_path=u.get("audio_path", ""),
            duration_sec=float(u.get("duration_sec", 0.0)),
            transcript=u.get("transcript", ""),
            annotation_source=(
                AnnotationSource(u["annotation_source"])
                if u.get("annotation_source")
                else None
            ),
            n_guessed_tokens=int(u.get("n_guessed_tokens", 0)),
            tokens=(
                None
                if u.get("tokens") is None
                else [
                    Token(
                        text=t["text"],
                        language=Language(t["language"]),
                        semantic_class=SemanticClass(t["semantic_class"]),
                        lid_confidence=float(t.get("lid_confidence", 1.0)),
                        start_ms=int(t.get("start_ms", 0)),
                        end_ms=int(t.get("end_ms", 0)),
                    )
                    for t in u["tokens"]
                ]
            ),
        )
        for u in data.get("utterances", [])
    ]
    return Corpus(
        name=data.get("name", ""),
        provenance=Provenance(data.get("provenance", Provenance.RECORDED.value)),
        speakers=speakers,
        sessions=sessions,
        utterances=utterances,
        root=root,
        ontology_version=data.get("ontology_version", ONTOLOGY_VERSION),
        protocol_version=data.get("protocol_version", "v1"),
        manifest_version=data.get("manifest_version", MANIFEST_VERSION),
        notes=data.get("notes", ""),
    )


