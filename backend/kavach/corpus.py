@dataclass(slots=True)
class SpeakerRecord:
    """One consenting speaker.

    `speaker_id` is a pseudonym and nothing here is a direct identifier. The
    link from pseudonym to person lives in the consent file, off this
    repository and outside `data/`, which is what makes a deletion request
    executable: destroy the link and the recordings and the manifest row
    becomes an orphan rather than a person.
    """

    speaker_id: str
    consent_ref: str = ""
    """Reference into the signed-consent register. Required when the corpus is
    RECORDED; `validate` fails without it."""

    gender: str = ""
    age_band: str = ""
    dominant_language: str = ""
    """Self-reported TA / EN / balanced. The §5.5 slice that most directly
    tests whether a VoxCeleb-trained embedding is fair to this population."""

    script_id: str = ""
    """Which read-speech script this speaker was given (`participant_scripts/`),
    empty for spontaneous speech.

    It is the speaker's language profile, and therefore the answer key: a
    SCRIPTED corpus is scored by asking whether the recovered CSBG matches the
    profile the script assigned, which is impossible without knowing which one
    they read. It also means a result on a scripted corpus can be inspected for
    the trivial failure -- two speakers given the same letter should *not*
    separate, and if they do, the separation is acoustic or accidental rather
    than lexical."""

    notes: str = ""

    def attributes(self) -> dict[str, str]:
        """Fairness-slice attributes, empty values dropped.

        Matches the `groups` argument of `eval.ablation.build_trials`, which
        ignores empty strings -- so an unanswered demographic question becomes
        an absent slice rather than a group named "".
        """
        return {
            k: v
            for k, v in (
                ("gender", self.gender),
                ("age_band", self.age_band),
                ("dominant_language", self.dominant_language),
            )
            if v
        }


@dataclass(slots=True)
class SessionRecord:
    """One sitting. The unit enrolment and probe speech are split on."""

    session_id: str
    speaker_id: str
    recorded_on: str = ""
    """ISO date. Cross-session stability is a claim about *time*, so a corpus
    whose sessions are twenty minutes apart cannot support §5.3 -- record the
    date and let the paper state the gap."""

    device: str = ""
    environment: Environment | None = None

    def attributes(self) -> dict[str, str]:
        return {
            k: v
            for k, v in (
                ("device", self.device),
                ("environment", self.environment.value if self.environment else ""),
            )
            if v
        }


@dataclass(slots=True)
class UtteranceRecord:
    """One answer to one prompt, with its annotation if it has been tagged.

    `tokens is None` and `tokens == []` mean different things and are kept
    distinct: the first is "not yet tagged", the second is "tagged, and the
    speaker said nothing scoreable". Collapsing them would let an untagged
    corpus build graphs sitting entirely at the smoothing prior and score
    near-chance against everything -- a system failure wearing the appearance
    of a weak result.
    """

    utterance_id: str
    session_id: str
    speaker_id: str
    prompt_id: str = ""
    audio_path: str = ""
    """Relative to the corpus root. Absolute paths break the day the corpus
    moves, and this one holds voiceprints, so it will be moved."""

    duration_sec: float = 0.0
    transcript: str = ""

    tokens: list[Token] | None = None
    annotation_source: AnnotationSource | None = None
    n_guessed_tokens: int = 0
    """Tokens the LID pipeline could not resolve and guessed. Mirrors
    `lid.pipeline.PipelineStats.fallback_guesses`; `Corpus.reportability`
    applies the same rule `PipelineStats.is_corpus_grade` does rather than
    inventing a second standard."""

    @property
    def is_annotated(self) -> bool:
        return self.tokens is not None

    def to_utterance_tokens(self) -> UtteranceTokens:
        """The shape everything downstream reads.

        Raises:
            ValueError: If the utterance has not been annotated. Returning an
                empty token list instead would silently contribute nothing to
                a CSBG while looking like a successful load.
        """
        if self.tokens is None:
            raise ValueError(
                f"utterance {self.utterance_id!r} has no annotation; "
                "run the LID pipeline before building graphs"
            )
        return UtteranceTokens(
            utterance_id=self.utterance_id,
            tokens=list(self.tokens),
            speaker_id=self.speaker_id,
            transcript=self.transcript,
        )


