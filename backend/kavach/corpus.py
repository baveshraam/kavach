@dataclass(slots=True)
class Corpus:
    """A loaded manifest, plus the queries the evaluation needs."""

    name: str
    provenance: Provenance
    speakers: list[SpeakerRecord] = field(default_factory=list)
    sessions: list[SessionRecord] = field(default_factory=list)
    utterances: list[UtteranceRecord] = field(default_factory=list)
    root: Path | None = None
    ontology_version: str = ONTOLOGY_VERSION
    protocol_version: str = "v1"
    manifest_version: str = MANIFEST_VERSION
    notes: str = ""

    # ------------------------------------------------------------- indexes

    def speaker(self, speaker_id: str) -> SpeakerRecord | None:
        return next((s for s in self.speakers if s.speaker_id == speaker_id), None)

    def session(self, session_id: str) -> SessionRecord | None:
        return next((s for s in self.sessions if s.session_id == session_id), None)

    @property
    def speaker_ids(self) -> list[str]:
        return [s.speaker_id for s in self.speakers]

    def sessions_of(self, speaker_id: str) -> list[SessionRecord]:
        """This speaker's sessions, ordered by date then id.

        Ordering is deterministic so "hold out the last session" means the same
        thing on every machine. Undated sessions sort first, which is the
        conservative placement: they end up in enrolment rather than silently
        becoming the held-out probe.
        """
        rows = [s for s in self.sessions if s.speaker_id == speaker_id]
        return sorted(rows, key=lambda s: (s.recorded_on or "", s.session_id))

    def utterances_of(
        self, speaker_id: str, *, session_id: str | None = None
    ) -> list[UtteranceRecord]:
        return [
            u
            for u in self.utterances
            if u.speaker_id == speaker_id
            and (session_id is None or u.session_id == session_id)
        ]

    def annotated(self) -> list[UtteranceRecord]:
        return [u for u in self.utterances if u.is_annotated]

    # ------------------------------------------------------------- loading

    def tokens_by_speaker(
        self, *, session_ids: Iterable[str] | None = None
    ) -> dict[str, list[UtteranceTokens]]:
        """The `dict[speaker_id, list[UtteranceTokens]]` the evaluation takes.

        Un-annotated utterances are skipped rather than raising, because a
        collection week legitimately has some; `reportability` is where that
        gets counted and objected to.

        Args:
            session_ids: Restrict to these sessions. None takes all.
        """
        wanted = set(session_ids) if session_ids is not None else None
        out: dict[str, list[UtteranceTokens]] = {}
        for u in self.utterances:
            if not u.is_annotated:
                continue
            if wanted is not None and u.session_id not in wanted:
                continue
            out.setdefault(u.speaker_id, []).append(u.to_utterance_tokens())
        return out

    def groups(self) -> dict[str, dict[str, str]]:
        """Speaker attributes for `fairness_slices`.

        Session attributes (device, environment) are folded in only when a
        speaker's sessions agree on them. A speaker recorded on two devices has
        no single device, and asserting one would put their trials in a slice
        that half of their audio contradicts.
        """
        out: dict[str, dict[str, str]] = {}
        for spk in self.speakers:
            attrs = spk.attributes()
            sessions = self.sessions_of(spk.speaker_id)
            for key in ("device", "environment"):
                values = {s.attributes().get(key, "") for s in sessions}
                values.discard("")
                if len(values) == 1:
                    attrs[key] = values.pop()
            out[spk.speaker_id] = attrs
        return out

    # ------------------------------------------------------- certification

    def reportability(self) -> list[str]:
        """Reasons this corpus may not be reported, empty if there are none.

        A list rather than a bool because the reasons are actionable and
        different: simulated speech is never fixable, missing annotation is a
        pipeline run away, and guessed tokens want an API key. Callers that
        want a bool can test emptiness; callers writing a paper want the list.
        """
        reasons: list[str] = []

        _WHY_NOT = {
            Provenance.SIMULATED: (
                "speakers differ by construction, so separating them measures "
                "the estimator, not the hypothesis"
            ),
            Provenance.SCRIPTED: (
                "speakers read authored text, so a CSBG recovers the profile the "
                "script assigned; the acoustic and integrity branches are "
                "unaffected, but no §5.1 claim about natural code-switching "
                "follows from it"
            ),
            Provenance.AUGMENTED: "augmented copies are not independent speakers",
        }
        if not self.provenance.is_reportable:
            reasons.append(
                f"provenance is {self.provenance.value}: "
                + _WHY_NOT.get(self.provenance, "not a recorded corpus")
            )

        unannotated = len(self.utterances) - len(self.annotated())
        if unannotated:
            reasons.append(
                f"{unannotated} of {len(self.utterances)} utterances are not annotated; "
                "they are skipped by the loader and contribute nothing to any graph"
            )

        guessed = sum(u.n_guessed_tokens for u in self.annotated())
        if guessed:
            reasons.append(
                f"{guessed} tokens were guessed by the LID fallback, so the "
                "annotation is not corpus-grade (see PipelineStats.is_corpus_grade)"
            )

        single = [s for s in self.speaker_ids if len(self.sessions_of(s)) < 2]
        if single:
            reasons.append(
                f"{len(single)} speakers have one session, so no cross-session "
                "trial exists for them and §5.3 cannot be computed on this corpus"
            )

        if self.ontology_version != ONTOLOGY_VERSION:
            reasons.append(
                f"annotated under ontology {self.ontology_version}, code is at "
                f"{ONTOLOGY_VERSION}; graphs across versions are not comparable"
            )

        return reasons

    def validate(self, *, check_audio: bool = False) -> list[str]:
        """Structural problems, empty if the manifest is sound.

        Separate from `reportability`: this catches a *broken* manifest,
        that one catches a *sound but unpublishable* corpus. A corpus can be
        perfectly valid and still not be evidence about anything.

        Args:
            check_audio: Also verify every `audio_path` resolves. Off by
                default because a manifest is frequently inspected on a machine
                that does not hold the recordings -- `data/` never leaves the
                one it was recorded on.
        """
        problems: list[str] = []

        if self.manifest_version != MANIFEST_VERSION:
            problems.append(
                f"manifest version {self.manifest_version!r} != {MANIFEST_VERSION!r}"
            )

        for name, ids in (
            ("speaker", [s.speaker_id for s in self.speakers]),
            ("session", [s.session_id for s in self.sessions]),
            ("utterance", [u.utterance_id for u in self.utterances]),
        ):
            duplicates = sorted({i for i, n in Counter(ids).items() if n > 1})
            if duplicates:
                problems.append(f"duplicate {name} ids: {duplicates}")

        known_speakers = set(self.speaker_ids)
        known_sessions = {s.session_id for s in self.sessions}

        for s in self.sessions:
            if s.speaker_id not in known_speakers:
                problems.append(
                    f"session {s.session_id!r} references unknown speaker {s.speaker_id!r}"
                )

        for u in self.utterances:
            if u.speaker_id not in known_speakers:
                problems.append(
                    f"utterance {u.utterance_id!r} references unknown speaker {u.speaker_id!r}"
                )
            if u.session_id not in known_sessions:
                problems.append(
                    f"utterance {u.utterance_id!r} references unknown session {u.session_id!r}"
                )
            else:
                session = self.session(u.session_id)
                if session and session.speaker_id != u.speaker_id:
                    problems.append(
                        f"utterance {u.utterance_id!r} claims speaker {u.speaker_id!r} "
                        f"but its session belongs to {session.speaker_id!r}"
                    )
            if u.prompt_id and u.prompt_id not in PROMPTS_BY_ID:
                problems.append(
                    f"utterance {u.utterance_id!r} cites unknown prompt {u.prompt_id!r}"
                )
            if u.n_guessed_tokens and not u.is_annotated:
                problems.append(
                    f"utterance {u.utterance_id!r} reports guessed tokens but has no annotation"
                )

        # Consent is a hard requirement, not a warning. See §9. It attaches to
        # every corpus whose audio came out of a human, which is RECORDED and
        # SCRIPTED both: what consent covers is the voiceprint, and a scripted
        # speaker's voice is exactly as clonable for having read invented words.
        if self.provenance in (Provenance.RECORDED, Provenance.SCRIPTED):
            missing = sorted(s.speaker_id for s in self.speakers if not s.consent_ref)
            if missing:
                problems.append(
                    f"{self.provenance.value} speakers without a consent reference: "
                    f"{missing}. Recording a voiceprint without a signed consent "
                    "record is not a data-hygiene issue, it is the reason this "
                    "corpus cannot be used at all."
                )

        if check_audio:
            root = self.root or Path()
            for u in self.utterances:
                if u.audio_path and not (root / u.audio_path).exists():
                    problems.append(
                        f"utterance {u.utterance_id!r}: missing audio {u.audio_path!r}"
                    )

        return problems

    # ------------------------------------------------------------ coverage

    def coverage(self, *, smoothing: SmoothingConfig | None = None) -> CoverageReport:
        return coverage_report(self, smoothing=smoothing)

    # --------------------------------------------------------- serialising

    def to_dict(self) -> dict[str, Any]:
        return {
            "manifest_version": self.manifest_version,
            "name": self.name,
            "provenance": self.provenance.value,
            "ontology_version": self.ontology_version,
            "protocol_version": self.protocol_version,
            "notes": self.notes,
            "speakers": [
                {
                    "speaker_id": s.speaker_id,
                    "consent_ref": s.consent_ref,
                    "gender": s.gender,
                    "age_band": s.age_band,
                    "dominant_language": s.dominant_language,
                    "script_id": s.script_id,
                    "notes": s.notes,
                }
                for s in self.speakers
            ],
            "sessions": [
                {
                    "session_id": s.session_id,
                    "speaker_id": s.speaker_id,
                    "recorded_on": s.recorded_on,
                    "device": s.device,
                    "environment": s.environment.value if s.environment else None,
                }
                for s in self.sessions
            ],
            "utterances": [
                {
                    "utterance_id": u.utterance_id,
                    "session_id": u.session_id,
                    "speaker_id": u.speaker_id,
                    "prompt_id": u.prompt_id,
                    "audio_path": u.audio_path,
                    "duration_sec": u.duration_sec,
                    "transcript": u.transcript,
                    "annotation_source": (
                        u.annotation_source.value if u.annotation_source else None
                    ),
                    "n_guessed_tokens": u.n_guessed_tokens,
                    "tokens": (
                        None
                        if u.tokens is None
                        else [
                            {
                                "text": t.text,
                                "language": t.language.value,
                                "semantic_class": t.semantic_class.value,
                                "lid_confidence": t.lid_confidence,
                                "start_ms": t.start_ms,
                                "end_ms": t.end_ms,
                            }
                            for t in u.tokens
                        ]
                    ),
                }
                for u in self.utterances
            ],
        }


