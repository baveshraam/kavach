@dataclass(frozen=True, slots=True)
class ElicitationPrompt:
    """One question put to a speaker, and the classes it is meant to produce.

    `target_classes` is a *hypothesis about the question*, not a label on the
    answer. `coverage_report` checks it against what the speaker actually said,
    and a prompt whose targets never appear is a broken question -- which is
    worth knowing before thirty people have answered it.
    """

    prompt_id: str
    text_en: str
    text_ta: str
    target_classes: tuple[SemanticClass, ...]

    elicits_phrase: bool = True
    """False for questions answerable with a bare noun.

    §5.1.1 is the reason this field exists: the *fact* in an answer is
    stealable, and what the CSBG measures is the wrapper the speaker puts round
    it. "What is your mother's name?" answered "Lakshmi" has no wrapper and
    gives the CSBG nothing. Such a prompt is not forbidden -- it is a useful
    control -- but it must be identifiable in the results, or its null result
    will be read as a failure of the hypothesis instead of the question.
    """


